class FakeWorker:
    base = m.WORKER

    def __init__(self):
        self.calls = []
        self.owner = None
        self.acked = False
        self.fail_ack = False
        self.lose_ack = False
        self.report = copy.deepcopy(REPORT)
        self.conflict = False
        self.before_claim = None

    def request(self, method, path, payload):
        self.calls.append((method, path, payload))
        if method == 'POST':
            if self.before_claim:
                self.before_claim(payload)
            if self.conflict or (self.owner and self.owner != payload['claimId']):
                m.fail('Worker POST failed (HTTP 409).')
            self.owner = payload['claimId']
            claim = {'id': ID, 'claimId': self.owner, 'token': TOKEN}
            if self.acked:
                claim['issueUrl'] = m.ISSUES + '45'
            else:
                claim['report'] = self.report
            return claim
        if method == 'DELETE':
            if self.fail_ack:
                m.fail('Worker DELETE failed.')
            assert payload == {'claimId': self.owner, 'token': TOKEN, 'issueUrl': m.ISSUES + '45'}
            self.acked = True
            if self.lose_ack:
                self.lose_ack = False
                m.fail('Lost ACK response.')
            return {'ok': True}
        raise AssertionError(method)


class FakeGitHub(m.GitHub):
    def __init__(self):
        self.issue = None
        self.calls = []
        self.labels = {}
        self.fail_create = False
        self.lose_create = False
        self.bad_verify = False
        self.closed = False

    def request(self, method, endpoint, payload=None):
        self.calls.append((method, endpoint, payload))
        if endpoint.startswith(m.LABELS):
            if method == 'GET':
                return [{'name': name} for name in self.labels]
            if method == 'POST':
                self.labels[payload['name']] = payload
                return payload
        if endpoint == m.API + '/45/labels' and method == 'POST':
            self.issue['labels'] += [{'name': label} for label in payload['labels']]
            return self.issue['labels']
        if endpoint == m.API + '/45' and method == 'PATCH':
            self.issue.update(payload)
            return self.issue
        if method == 'GET' and '?' in endpoint:
            return [] if self.issue is None else [self.issue]
        if method == 'POST':
            if self.fail_create:
                m.fail('Create failed.')
            self.issue = {'number': 45, 'html_url': m.ISSUES + '45',
                          'url': 'https://api.github.com/' + m.API + '/45',
                          'title': payload['title'], 'body': payload['body'], 'labels': [{'name': label} for label in payload['labels']],
                          'state': 'closed' if self.closed else 'open'}
            if self.lose_create:
                m.fail('Create response lost.')
            return self.issue
        if method == 'GET':
            if self.bad_verify:
                return {**self.issue, 'html_url': 'https://github.com/other/repo/issues/45'}
            return self.issue
        raise AssertionError(endpoint)

    @property
    def creates(self):
        return sum(method == 'POST' and endpoint == m.API for method, endpoint, _ in self.calls)


class CredentialFileTests(unittest.TestCase):
    def args(self, path):
        return type('Args', (), {'credential_file': path})()

    def test_missing_file_has_its_own_message(self):
        with tempfile.TemporaryDirectory() as d:
            with self.assertRaises(m.ImportErrorSafe) as caught:
                m.credential(self.args(os.path.join(d, 'absent')))
        self.assertIn('No report credential found', str(caught.exception))
        self.assertIn('--credential-file', str(caught.exception))
        self.assertNotIn('mode 600', str(caught.exception))

    def test_wrong_mode_keeps_permission_message(self):
        with tempfile.TemporaryDirectory() as d:
            path = os.path.join(d, 'token')
            with open(path, 'w') as f:
                f.write('secret')
            os.chmod(path, 0o644)
            with self.assertRaises(m.ImportErrorSafe) as caught:
                m.credential(self.args(path))
            self.assertIn('mode 600', str(caught.exception))
            self.assertNotIn('No report credential found', str(caught.exception))
            os.chmod(path, 0o600)
            self.assertEqual(m.credential(self.args(path)), 'secret')


