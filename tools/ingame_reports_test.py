class ImageGitHub(FakeGitHub):
    def __init__(self):
        super().__init__()
        self.files = {}
        self.image_calls = []
        self.fail_upload = False
        self.lose_upload = False
        self.fail_image_get = False
        self.remove_embed = False

    def request(self, method, endpoint, payload=None, *, allow_not_found=False):
        if endpoint.startswith(m.CONTENTS):
            self.image_calls.append((method, endpoint, payload))
            if method == 'GET':
                if self.fail_image_get:
                    m.fail('Contents read failed, not a typed 404.')
                file = self.files.get(endpoint.split('?')[0])
                if file is None:
                    raise m.GitHubNotFound('Explicit fixture HTTP 404.')
                return copy.deepcopy(file)
            if method == 'PUT':
                if self.fail_upload:
                    m.fail('Upload failed.')
                if endpoint in self.files:
                    m.fail('Concurrent Contents collision.')
                data = m.base64.b64decode(payload['content'])
                name = endpoint.rsplit('/', 1)[1][:-4]
                self.store(data, name[:36], name[36:])
                if self.lose_upload:
                    self.lose_upload = False
                    m.fail('Image PUT response lost.')
                return {'content': self.files[endpoint]}
            raise AssertionError(method)
        if method == 'POST' and endpoint == m.API:
            ident = payload['body'].split('\n', 1)[0].split(':')[-1].split(' ')[0]
            for suffix, needle in (('', 'Bildbedömning'), ('-2', 'Fotobedömning')):
                if needle in payload['body']:
                    assert m.CONTENTS + m.image_path(ident, suffix) in self.files, 'Originals must be committed before issue creation.'
        response = super().request(method, endpoint, payload)
        if self.remove_embed and method == 'GET' and '?' not in endpoint and isinstance(response, dict):
            return {**response, 'body': response['body'].split('\nBildbedömning')[0]}
        return response

    def store(self, data, ident=ID, suffix=''):
        self.files[m.CONTENTS + m.image_path(ident, suffix)] = {
            'type': 'file', 'path': m.image_path(ident, suffix), 'size': len(data),
            'encoding': 'base64', 'content': m.base64.b64encode(data).decode() + '\n',
            'sha': m.hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest(),
            'html_url': m.image_url(ident, suffix)}

    @property
    def uploads(self):
        return sum(method == 'PUT' for method, _, _ in self.image_calls)


