export function notices() {
  const pictureFiles = fs.readdirSync(path.join(ROOT, 'textures')).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();
  const unlisted = pictureFiles.filter((f) => !PICTURES.some(([name]) => name === f));
  if (unlisted.length) throw new Error(`textures/ has pictures without a notice entry in PICTURES: ${unlisted.join(', ')}`);
  const elevation = JSON.parse(read('data/elevation.json'));
  const models = fs.readdirSync(path.join(ROOT, 'models')).filter((f) => f.endsWith('.glb')).sort();
  return `# Third-party notices — Lunden for Windows

GENERATED by \`tools/unreal-engine/notices.mjs\` from the web version's attribution files (#2245); do not edit by hand.
Ships with the Windows package (#2248). Repository: https://github.com/solwation/lunden-3d-apartment

## Music (Creative Commons Attribution 4.0)

Embedded verbatim from \`music/CREDITS.md\` (links in it are relative to the repository's \`music/\` folder).

${demote(read('music/CREDITS.md'))}

## Font: Kalam (SIL Open Font License 1.1)

${read('data/fonts/README.md')}

\`\`\`text
${read('data/fonts/Kalam-OFL.txt')}
\`\`\`

## Terrain: Copernicus DEM GLO-30

The ground levels (\`data/elevation.json\`, ${elevation.source}) are used under the Copernicus DEM licence:

> ${elevation.licence}

Contains modified Copernicus data.

## Elevation points: Lantmäteriet

River and road height checks (\`docs/references/elevation-hoje-a/\`) use Lantmäteriet's Markhöjdmodell (1 m grid,
RH 2000) via the kart-api.se point API: © Lantmäteriet, licensed under CC BY 4.0
(https://creativecommons.org/licenses/by/4.0/).

## Map data: OpenStreetMap

Building footprints, roads, paths and other site geometry (\`SITE\` in \`src/config.js\`, snapshots in
\`docs/references/\`) are derived from OpenStreetMap data: © OpenStreetMap contributors, available under the Open
Database License (ODbL) 1.0 (https://www.openstreetmap.org/copyright).

## Pictures in the apartment (\`textures/\`)

The pictures on L1007's walls and the cat's photo frame are the apartment owner's own photographs of the family's
pictures, retouched for the game, and one family home drawing. They are included in this Windows version
with the owner's approval (#2289) and are not licensed for any other use; the artworks they show remain their
makers' work. Not part of the public web copy.

${PICTURES.map(([file, what, origin]) => `- \`textures/${file}\`: ${what}. Source: ${origin}.`).join('\n')}

## 3D models

Every model file (${models.map((m) => `\`${m}\``).join(', ')}) and all generated geometry are the project's own work,
exported from its JavaScript recipes (\`models/ATTRIBUTION.md\`). No third-party model, texture pack, Fab/Marketplace or
Starter Content asset is included.
`;
}

const text = notices();
if (process.argv.includes('--check')) {
  const ok = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') === text;
  console.log(ok ? `${path.relative(ROOT, OUT)} is current` : `${path.relative(ROOT, OUT)} is OUT OF DATE: run node tools/unreal-engine/notices.mjs`);
  process.exit(ok ? 0 : 1);
}
fs.writeFileSync(OUT, text);
console.log(`wrote ${path.relative(ROOT, OUT)} (${text.length} chars)`);
