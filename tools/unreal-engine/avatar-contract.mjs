// #2290: the avatar values Unreal's rig takes from the web, written to tools/unreal-engine/avatar-contract.json.
//
// The logical hit zones (the shared head contract, docs/development/storage.md "Current shared head contract") and the
// motion thresholds come from src/config.js; build_avatar_rig.py writes them into BP_LundenAvatar and
// ABP_LundenAvatar, so no web number is copied into a graph by hand. `samples` are the web's own answers
// (rifleBoxHeadContact, playerBodySegment, rifleHeadBaseY) for rays through a standard figure (tall = 1) standing,
// crouched, seated and lying; tests/test_avatar_rig.py casts the same rays through the Unreal zones (1 cm).
//
// Run (Node, no browser):  node tools/unreal-engine/avatar-contract.mjs [--check]
// --check fails when the committed file no longer matches src/config.js (rerun without --check, then build_avatar_rig.py).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url)), root = path.resolve(here, '../..');
const out = path.join(here, 'avatar-contract.json');
globalThis.window ??= globalThis; globalThis.localStorage ??= { getItem: () => null, setItem() {}, removeItem() {} };
const C = await import(pathToFileURL(path.join(root, 'src/config.js')).href);
const H = C.PVP_HEAD_BOXES, r4 = (v) => Math.round(v * 1e4) / 1e4;

// A seed whose look is the unscaled standard figure (tall 1, no neck change): the contract's own frame.
let seed = null;
for (let i = 0; i < 1000 && seed === null; i++) {
  const s = `lunden-${i}`, look = C.avatarLook(s);
  if (look.tall === 1 && !C.avatarShape('neck', look.neck)) seed = s;
}
if (seed === null) throw new Error('avatar-contract: no seed with tall 1 and the standard neck');

// The rest poses' hip and lean (src/config.js rifleBoxPose: SEAT_SIT, SEAT_LEAN and REST are not all exported), read
// back from the web's own body segment: it turns about the hip by the lean, as the head boxes do.
function restFrame(pose) {
  const [a, b] = C.playerBodySegment(seed, { p: [0, 0, 0], r: 0, c: 0, pose });
  const fa = -a[2], fb = -b[2], dy = C.COMBAT.body[1] - C.COMBAT.body[0];
  const lean = Math.atan2(-(fb - fa) / dy, (b[1] - a[1]) / dy), d0 = C.COMBAT.body[0] - H.hipY;
  return { hipY: r4(a[1] - Math.cos(lean) * d0), hipZ: r4(fa + Math.sin(lean) * d0), lean: r4(lean) };
}
const SEAT = restFrame(1), LIE = restFrame(2);

// Avatar frame: forward f (the way the figure faces), left l, up y, metres; the web figure at the origin with r = 0
// faces -z (its left is -x).
const web = ([f, l, y]) => [-l, y, -f];
const states = [
  { name: 'stand', state: { c: 0 } },
  { name: 'crouch-half', state: { c: 0.5 } },
  { name: 'crouch', state: { c: 1 } },
  { name: 'sit', state: { c: 0, pose: 1 } },
  { name: 'lie', state: { c: 0, pose: 2 } },
];
const columns = [];
for (let f = -0.3; f <= 0.601; f += 0.05) for (const l of [0, 0.06]) columns.push([r4(f), l]);
const rows = [];
for (let y = 0.3; y <= 1.901; y += 0.05) for (const l of [0, 0.06]) rows.push([r4(y), l]);

function contact(state, from, dir) {
  const hit = C.rifleBoxHeadContact(seed, { p: [0, 0, 0], r: 0, ...state }, web(from), web(dir), 10);
  if (!hit) return null;
  const [x, y, z] = hit.point;
  return [r4(-z), r4(-x), r4(y)]; // back to the avatar frame
}
// A ray whose answer changes within 1.5 cm sideways grazes an edge: the test accepts its answer or a neighbour's.
function sample(state, from, dir, axis, shift) {
  const hit = contact(state, from, dir);
  let edge = false;
  const alt = [];
  for (const d of [-0.015, 0.015]) {
    const moved = from.slice(); moved[shift] += d;
    const other = contact(state, moved, dir);
    alt.push(other ? other[axis] : null);
    if ((other === null) !== (hit === null) || (hit && Math.abs(other[axis] - hit[axis]) > 0.02)) edge = true;
  }
  // `alt`: the answers 1.5 cm to either side, which an edge ray may match instead (floating-point grazing)
  return { from, dir, hit: hit ? hit[axis] : null, ...(edge ? { edge: true, alt } : {}) };
}

const samples = states.map(({ name, state }) => {
  const full = { p: [0, 0, 0], r: 0, ...state };
  const rays = [];
  for (const [f, l] of columns) {
    rays.push(sample(state, [f, l, 3], [0, 0, -1], 2, 0));
    rays.push(sample(state, [f, l, 0], [0, 0, 1], 2, 0));
  }
  for (const [y, l] of rows) rays.push(sample(state, [3, l, y], [-1, 0, 0], 0, 2));
  const body = C.playerBodySegment(seed, full).map((p) => { const [x, y, z] = p; return [r4(-z), r4(-x), r4(y)]; });
  return { name, state, headBaseY: r4(C.rifleHeadBaseY(seed, full)), body, rays };
});

const contract = {
  formatVersion: 1,
  what: '#2290: the web avatar values for Unreal (build_avatar_rig.py, tests/test_avatar_rig.py). Metres and radians; ' +
    'avatar frame: forward, left, up from the feet. Generated by tools/unreal-engine/avatar-contract.mjs; never edit by hand.',
  source: 'src/config.js PVP_HEAD_BOXES, AVATAR_CROUCH, COMBAT.body/hitRadius, REST (sit/lie frames read back from playerBodySegment), AVATAR_GAIT.run, AVATAR.walkSpeed, PLAYER',
  head: { version: H.version, boxes: H.boxes, hipY: H.hipY, hipDrop: H.hipDrop, hipForward: H.hipForward, crouchLean: H.crouchLean },
  body: { low: C.COMBAT.body[0], high: C.COMBAT.body[1], radius: C.COMBAT.hitRadius },
  poses: { sit: SEAT, lie: LIE },
  motion: {
    walk: C.PLAYER.walk, run: C.PLAYER.run, crouchSpeed: C.PLAYER.crouchSpeed, legsWalkAbove: C.AVATAR.walkSpeed,
    gaitRun: C.AVATAR_GAIT.run, crouchTime: C.AVATAR_CROUCH.time, crouchStep: C.AVATAR_CROUCH.step,
    standardHeight: C.AVATAR_HEIGHT.base / 100, eye: C.PLAYER.eye, crouchEye: C.PLAYER.crouchEye,
  },
  seed,
  samples,
};
// One ray per line keeps the file readable in a diff.
const text = JSON.stringify(contract, (k, v) => (k === 'rays' ? v.map((r) => `@@${JSON.stringify(r)}@@`) : v), 1)
  .replace(/"@@(.*?)@@"/g, (m, r) => JSON.parse(`"${r}"`)) + '\n';
if (process.argv.includes('--check')) {
  const old = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (old !== text) { console.error(`avatar-contract: ${path.relative(root, out)} is stale; run node tools/unreal-engine/avatar-contract.mjs`); process.exit(1); }
  console.log(`avatar-contract: ${path.relative(root, out)} matches src/config.js (${samples.reduce((n, s) => n + s.rays.length, 0)} rays)`);
} else {
  fs.writeFileSync(out, text);
  console.log(`avatar-contract: wrote ${path.relative(root, out)} (seed ${seed}, ${samples.reduce((n, s) => n + s.rays.length, 0)} rays)`);
}
