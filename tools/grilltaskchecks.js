import * as THREE from 'three';
import { TasksManager } from '../src/tasks.js';
import { Chicken } from '../src/chicken.js';
import { Grill } from '../src/grill.js';
import { Life } from '../src/life.js';
import { heldItem } from '../src/holdable.js';
import { resetStats, stats, bump, totalScore, taskReward } from '../src/stats.js';
import { CHICKEN as C, SCORE, TASK_POOL } from '../src/config.js';

// #710: actual domain classes, isolated small scene; also called by taskstest's full-app wrapper.
export function runGrillTaskChecks(check) {
  resetStats();
  const scene = new THREE.Scene(), camera = new THREE.PerspectiveCamera();
  const life = new Life({ scene, camera });
  const tasks = new TasksManager({ life, scene });
  const grill = new Grill(); scene.add(grill.object); grill.onLit = () => life.emit('grillLit', { surface: 'grill' });
  const fridge = { object: new THREE.Group(), shelfSpot: new THREE.Vector3(0, 1, 0), isOpen: true }; scene.add(fridge.object);
  const bird = new Chicken(scene, camera, fridge, null, { on: true }); bird.initLife(life, grill); grill.occupied = () => bird.inGrill;
  bird.onCooked = () => bump('grilledChicken');
  const task = () => tasks.tasks.find(t => t.id === 'grillChicken');
  const heat = seconds => { for (let t = 0; t < seconds - 1e-6; t += .1) { bird.update(Math.min(.1, seconds - t)); grill.update(Math.min(.1, seconds - t)); } };
  const record = () => JSON.parse(JSON.stringify(life.serialize()));
  const openSlot = () => { life.emit('washed', { what: 'spoon' }); life.emit('vacuumed', { amount: 1 }); life.emit('hallTidied', { item: { type: 'hallJacket' } }); life.emit('hallTidied', { item: { type: 'hallShoes' } }); };
  const amount = () => stats.taskCounts.grillChicken ?? 0;
  check(tasks.activeTasks().length === 3 && !tasks.isShown('grillChicken'), '#710: initial pool has three and chicken discovery is hidden');
  tasks.read(); check(tasks.isShown('tidyHall') && !tasks.isShown('grillChicken'), '#710: reading still discovers hall, never reveals chicken early');
  grill.set(true); bird.take(); bird.intoPan();
  check(task().active && task().shown && tasks.activeTasks().length === 3, '#710: actual refused pan attempt discovers chicken and gives one capped slot');
  check(!task().completedGoals.size && amount() === 0, '#710: pan attempt cannot complete grill goals or reward');
  tasks.setHints(false); check(!tasks.currentHint(), '#710: hints off suppresses detailed instructions');
  tasks.setHints(true);
  bird.intoGrill();
  check(task().completedGoals.has('fire') && task().completedGoals.has('place'), '#710: actual raw placement on already-lit grill counts lighting and placement');
  const partial = record(), score = totalScore(); life.load(partial);
  check(task().active && task().placedBird === bird.id && task().completedGoals.size === 2 && totalScore() === score, '#710: partial progress and bird identity restore without reward');
  const goldenEvent = { item: { id: bird.id, type: 'chicken', machine: { cooked: true, burnt: false } }, state: 'golden', surface: 'pan' };
  life.emit('grilled', goldenEvent); life.emit('chickenTaken', goldenEvent);
  check(!task().isDone && !task().grilledBird, '#710: pan events never count cooking or golden pickup');
  life.emit('grilled', { ...goldenEvent, surface: 'grill', item: { ...goldenEvent.item, id: 'other-bird' } });
  check(!task().grilledBird, '#710: another bird identity cannot supply golden completion');
  heat(C.cookSeconds + .1);
  check(task().grilledBird === bird.id && !task().isDone && amount() === 0, '#710: actual grilling records golden state but still needs pickup');
  const golden = record(); heat(C.burnSeconds); bird.take();
  check(bird.burnt && task().failed && amount() === 0 && tasks.activeTasks().length === 3, '#710: burnt cycle enters cooldown without reward and refills pool');
  const failed = record(), failedId = bird.id; life.load(failed); tasks.update(TASK_POOL.cooldown - 1);
  check(task().failed && bird.id === failedId && amount() === 0, '#710: failed cooldown reload preserves same burnt bird before deadline');
  tasks.update(1); openSlot(); check(bird.id !== failedId && !bird.done && amount() === 0, '#710: failed cooldown supplies new raw bird without reward');
  life.load(golden); const before = totalScore(); bird.take();
  check(task().isDone && amount() === 1 && totalScore() - before === 45 && SCORE.tasks.grillChicken.first === 45, '#710: actual golden pickup awards exactly the displayed 45 points');
  check(tasks.activeTasks().length === 3 && !task().active, '#710: completion immediately refills three active tasks');
  const doneScore = totalScore(), completed = record(); bird.reset(); bird.take(); bird.putBack(); life.load(completed);
  check(amount() === 1 && totalScore() === doneScore && task().isDone && bird.done && bird.rewarded, '#710: F, duplicate actions and completed reload do not reward or replenish');
  const id = bird.id; tasks.update(TASK_POOL.cooldown - 1);
  check(bird.id === id && bird.done && !task().replenished, '#710: bird stays same cooked identity before cooldown deadline');
  const nearDeadline = record(); life.load(nearDeadline); tasks.update(1);
  check(bird.id === id && bird.done && !task().active, '#710: full pool at cooldown deadline keeps the cooked bird instead of exposing an untracked fresh reward');
  openSlot();
  check(bird.id !== id && !bird.done && !bird.rewarded && !bird.placed && !bird.held && bird.parts.every(p => !p.gone) && task().active, '#710: after cooldown an active slot and one new raw bird become available together');
  const freshId = bird.id, newBird = record(); life.load(newBird); tasks.update(.1);
  check(bird.id === freshId && amount() === 1, '#710: fresh generation persists and cannot replenish/reward again on reload');
  // A full pool retains queued eligibility; opening one slot activates the cooled-down task.
  tasks.update(.1);
  check(task().active && !task().completedGoals.size && !task().placedBird && taskReward('grillChicken') === 8, '#710: repeat becomes eligible with cleared cycle markers and smaller displayed +8');
  bird.take(); bird.intoGrill(); heat(C.cookSeconds + .1); const repeatBefore = totalScore(); bird.take();
  check(amount() === 2 && totalScore() - repeatBefore === 8, '#710: fresh repeat cycle awards +8 once');
  // Expired saved cooldown remains silent on load; the next ordinary played update renews once.
  const overdue = record(); overdue.x.tasks.elapsed = task().readyAt;
  const overdueId = bird.id; life.load(overdue);
  check(bird.id === overdueId && task().isDone && !task().replenished, '#710: loading an expired cooldown is silent and does not replace bird');
  tasks.update(0); openSlot(); check(bird.id !== overdueId && task().active, '#710: next played update handles expired pending renewal once');
  resetStats(); tasks.reset({ newChicken: true }); check(!task().shown && !task().active && !task().completions && !task().placedBird && !task().grilledBird && !task().readyAt, '#710: reset clears task discovery/cycle/cooldown markers');
  check(!bird.done && !bird.burnt && !bird.rewarded && totalScore() === 0, '#710: true statistics reset renews chicken alongside zeroed score, preventing a locked challenge');
  bird.take(); bird.intoGrill();
  check(task().shown && task().active && task().completedGoals.has('place'), '#710: finding the real raw grill route discovers the task without a pan attempt');
  heat(C.cookSeconds + .1); bird.take();
  check(amount() === 1 && task().isDone, '#710: direct grill discovery can complete and reward normally');
  resetStats(); tasks.reset({ newChicken: true });
  bird.take(); bird.intoGrill(); heat(C.cookSeconds + .1); bird.take();
  tasks.reset(); bird.intoPan();
  check(task().failed && !task().active, '#710: already-cooked bird discovered after older/reset task state enters recoverable cooldown');
  resetStats(); tasks.reset({ newChicken: true });
  // Capture the actual shared note CanvasTexture after discovery, with partial goal checks and all three tasks.
  tasks.read(); bird.take(); bird.intoPan(); bird.intoGrill();
  tasks.setHints(false);
  const cabinet = { door: new THREE.Group(), innerFace: { x: 0, width: .5, height: .8 }, isOpen: true };
  tasks.build3DCard(cabinet);
  check(tasks.activeTasks().length === 3 && taskReward('grillChicken') === 45 && task().completedGoals.has('place'), '#710: shared note has three active tasks, first reward and checked partial goals');
  const paper = tasks.cardTexture.image.toDataURL();
  const saved = record(); const restoreScore = totalScore(); life.load(saved);
  check(tasks.isShown('grillChicken') && task().placedBird === bird.id && totalScore() === restoreScore, '#710: discovered note/partial cycle reloads silently');
  resetStats(); tasks.reset({ newChicken: true }); bird.take(); bird.intoPan(); tasks.read();
  check(task().active && tasks.isShown('tidyHall') && tasks.activeTasks().length === 3, '#710: pan-first discovery remains active when note first reveals hall');
  resetStats(); tasks.reset({ newChicken: true }); bird.take(); bird.intoPan(); bird.intoGrill(); tasks.read();
  check(task().active && task().completedGoals.size === 2 && task().placedBird === bird.id && tasks.activeTasks().length === 3, '#710: first hall reading cannot displace an in-progress grill cycle');
  heat(C.cookSeconds + .1); bird.take();
  check(amount() === 1 && task().isDone, '#710: pan-first/read-hall/actual-grill flow still finishes once');
  return { paper, tasks, bird, life, scene, grill };
}
